// Alpha flagged layer indicator
bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {
    if (ctrl_timer > 0) {
        HSV hsv = {HSV_BLUE};
        hsv.v = hsv.v/2;

        uint16_t elapsed_time = timer_elapsed(ctrl_timer);

        if (elapsed_time < 1000 && ctrl_displaying) {
            bool first = false;
            bool update = false;
            if (update_timer == 0) {
                update_timer = timer_read();
                first = true;
            } else if (timer_elapsed(update_timer) > 30) {
                update_timer = timer_read();
                update = true;
            }
            if (first || update) {
                hsv.v = hsv.v * (1 - (elapsed_time / 1000.0f));
                RGB rgb = hsv_to_rgb(hsv);
                for (int i = 0; i < 40; i++) {
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
                }
            }
        } else {
            xprintf("matrix_scan_user: ");
            reset_ctrl_highlight();
            RGB rgb = {RGB_OFF};
            for (int i = 0; i < 40; i++) {
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
            }
        }
        return false;
    }

    uint8_t l = get_highest_layer(layer_state);
    if (l == last_layer) {
        return false;
    }
    last_layer = l;

    for (uint8_t i = led_min; i < led_max; i++) {
        switch (l) {
            case 1:
                if (HAS_FLAGS(g_led_config.flags[i], LED_FLAG_UNDERGLOW) || i == 57 || i == 52 || (i == 144 || i == 145 || i == 135 || i == 134)) {
                    // backlight_level(2);
                    HSV hsv = {137, 82, 237/3};
                    RGB rgb       = hsv_to_rgb(hsv);
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);  //set LEDs 1, 2, 3 to CYAN
                }
                break;
            case 2:
                if (HAS_FLAGS(g_led_config.flags[i], LED_FLAG_UNDERGLOW) || (i >= 147 && i <= 151)) {
                    HSV hsv = {16,201,100};
                    hsv.s = hsv.s;
                    if (HAS_FLAGS(g_led_config.flags[i], LED_FLAG_UNDERGLOW)) {
                        hsv.v = hsv.v/3;
                    }
                    RGB rgb       = hsv_to_rgb(hsv);
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
                }
                if (i == 50) { // R
                    HSV hsv = {HSV_RED};
                    hsv.v = hsv.v/3;
                    RGB rgb = hsv_to_rgb(hsv);
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
                }
                break;
            default:
                if (HAS_FLAGS(g_led_config.flags[i], LED_FLAG_UNDERGLOW) || (i >= 147 && i <= 151)) {
                    RGB rgb = {RGB_OFF};
                    rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
                    break;
                }
        }

    }
    return false;
}

