void reset_ctrl_highlight(void) {
    xprintf("set ctrl_timer to 0\n");
    ctrl_displaying = false;
    ctrl_timer = 0;
    update_timer = 0;
}

layer_state_t layer_state_set_user(layer_state_t state) {
    bool num_lock = host_keyboard_led_state().scroll_lock;
    uint16_t layer = get_highest_layer(state);
    xprintf("switch to layer %d\n", layer);
    switch (layer) {
            case 1:
                if (!num_lock) {
                    xprintf("turn on scroll lock\n");
                    register_code(KC_SCROLL_LOCK);
                    unregister_code(KC_SCROLL_LOCK);
                }
                break;
            default:
                if (num_lock) {
                    xprintf("turn off scroll lock\n");
                    register_code(KC_SCROLL_LOCK);
                    unregister_code(KC_SCROLL_LOCK);
                } else {
                    xprintf("scroll lock is not on\n");
                }
                break;
    }
    return state;
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case TCH_TOG:
            if (record->event.pressed) {
                touch_encoder_toggle();
            }
            return false;  // Skip all further processing of this key
        case KC_LCTL:
            if (!record->event.pressed) {
                HSV hsv = {HSV_RED};

                if (ctrl_pressed) {
                    xprintf("lctrl double pressed\n");
                    hsv.v = hsv.v/2;
                    ctrl_pressed = false;
                    xprintf("process_record_user: ");
                    reset_ctrl_highlight();
                    ctrl_timer = timer_read();
                    ctrl_displaying = true;
                } else {
                    xprintf("lctrl pressed\n");
                    hsv.v = hsv.v/3;
                    ctrl_pressed = true;
                }
                // RGB rgb = hsv_to_rgb(hsv);
                //rgb_matrix_set_color(74, RGB_RED);
            }
            break;
        default:
            // rgb_matrix_set_color(74, 0, 0, 0);
            ctrl_pressed = false;
            break;
    }
    return true;
}

