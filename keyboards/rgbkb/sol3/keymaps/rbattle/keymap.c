static void render_calcifer(void) {
    // Run animation
    if (timer_elapsed(timer) > FRAME_DURATION) {
        // Set timer to updated time
        timer = timer_read();

        // Increment frame
        current_frame = (current_frame + 1) % (sizeof(calcifer_allArray) / sizeof(calcifer_allArray[0]));

        // Draw frame to OLED

        oled_write_raw_P(calcifer_allArray[current_frame], frame_sizes[current_frame]);
    }
}

void oled_draw_horizontal_line_from_start(uint8_t startX, uint8_t y) {
    for (uint8_t i = startX; i < OLED_DISPLAY_HEIGHT; i++) {
        oled_write_pixel(i, y, true);
    }
}

void oled_draw_horizontal_line(uint8_t y) {
    oled_draw_horizontal_line_from_start(0, y);
}


void oled_white_background(uint8_t row, uint8_t startCol) {
    uint8_t start = row * OLED_DISPLAY_WIDTH / OLED_FONT_HEIGHT;
    oled_draw_horizontal_line_from_start(0, start - 1);
    for (uint8_t y = 0; y < 8; y++) {
        oled_draw_horizontal_line_from_start(startCol * OLED_FONT_WIDTH, y+start);
    }
}

uint8_t render_leds(uint8_t row)
{
    oled_write_ln_P(PSTR("LOCK"), true);
    // oled_white_background(row, 4);

    led_t led_state = host_keyboard_led_state();
    oled_write_P( PSTR("N"), led_state.num_lock );
    oled_write_P( PSTR(" "), false );
    oled_write_P( PSTR("C"), led_state.caps_lock );
    oled_write_P( PSTR(" "), false );
    oled_write_P( PSTR("S"), led_state.scroll_lock );
    return row+2;

}

uint8_t render_wpm(uint8_t row) {
    char wpm_str[10];
    oled_write_ln_P(PSTR("WPM"), true);
    // oled_white_background(row, 3);
    sprintf(wpm_str, "%d", get_current_wpm());
    oled_write_ln_P(PSTR(wpm_str), false);
    return row + 2;
}

uint8_t render_layer(uint8_t row) {
    // clang-format off
    const char* layer_names[] = {
        [0]  = "Base",
        [1]  = "Func",
        [2]  = "RGB",
    };
    // clang-format on

    oled_write_P(PSTR("LAYER"), true);
    // oled_white_background(5, 5);

    oled_write_ln_P(PSTR(layer_names[get_highest_layer(layer_state)]), false);
    return row + 2;
}

uint8_t render_rgb(uint8_t row) {
    if (rgb_matrix_config.enable > 0) {
        static char buffer[3] = {0};
        oled_write_ln_P(PSTR("RGB"), true);
        // oled_white_background(row, 3);
        snprintf(buffer, sizeof(buffer), "%d", rgb_matrix_config.mode);
        oled_write_ln_P(PSTR(buffer), false);
        return row + 2;
    }
    return row;
}

bool oled_task_user(void) {
    if (is_oled_on()) {
        if (last_input_activity_elapsed() > OLED_TIMEOUT) {
            oled_off();
        } else {
            // render_logo();


            render_calcifer();
            oled_draw_horizontal_line(36);
            uint8_t row = 5;
            oled_set_cursor(0, row);
            // font is 6x8
            // OLED is 128x32
            // since it is vertical, we have 32 pixels per row
            // there are 16 rows with 5.3 columns
            row = render_layer(row);

            row = render_wpm(row + 2);
            //> charsoled_max_chars(): 5
// > rowsoled_max_lines(): 16
            // print("chars");
            // print_val_dec(oled_max_chars());
            // print("rows");
            // print_val_dec(oled_max_lines());
            row = render_leds(row);

            row = render_rgb(row);
            while (row < oled_max_lines()) {
                oled_advance_page(true);
                row++;
            }
            // render_rgb_menu();
        }
    }



    return false;
}
